function battle(id,type='armored',hp=ENEMY_TYPES[type].hp){
  const state=engine.createNewState({now:1000,runId:'def-effects-'+id});state.phase='wave';state.wave=1;state.spawnIndex=engine.wavePlan(1).length;state.nextEnemyId=2;
  state.assignments[id]={...state.assignments[id],mode:'defend',padId:'p3',paid:true};
  state.enemies=[{...ENEMY_TYPES[type],id:1,type,hp,maxHp:hp,distance:5.2,slowUntil:0,slowFactor:0}];return state;
}
