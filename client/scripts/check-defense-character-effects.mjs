check('pause, repeated frames, old event IDs, hidden pages and run changes suppress replayed sound',()=>{
  const state=createDefenseEffectPreview('yuzu','skill'),id=state.effects[0].id,previous={runId:state.runId,elapsed:0,ids:[]};
  const current={runId:state.runId,elapsed:.1,active:true,paused:false,hidden:false};
  assert.equal(newDefenseSoundEvents(previous,current,state).length,1);
  for(const change of [{elapsed:0},{paused:true},{hidden:true},{active:false},{runId:'other'}])
    assert.equal(newDefenseSoundEvents(previous,{...current,...change},state).length,0);
  assert.equal(newDefenseSoundEvents({...previous,ids:[id]},current,state).length,0);
});
