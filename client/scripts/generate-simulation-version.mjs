import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const paths = ['src/app/simulation/tacticalSkillTable.js'];
for (const dir of ['src/app/simulation/_lib', 'src/utils']) {
  for (const file of readdirSync(new URL(`${dir}/`, root))) if (file.endsWith('.js')) paths.push(`${dir}/${file}`);
}
const hash = createHash('sha256');
for (const path of paths.sort()) hash.update(path).update('\0').update(readFileSync(new URL(path, root), 'utf8').replaceAll('\r\n', '\n')).update('\0');
const version = hash.digest('hex');
const target = new URL('src/app/simulation/_generated/simulationEngineVersion.js', root);
const content = `// Generated by scripts/generate-simulation-version.mjs.\nexport const SIMULATION_ENGINE_VERSION = '${version}';\n`;
let previous = '';
try { previous = readFileSync(target, 'utf8'); } catch { /* First generation. */ }
if (previous !== content) writeFileSync(fileURLToPath(target), content);
console.log(`SIMULATION_ENGINE_VERSION ${version}`);
